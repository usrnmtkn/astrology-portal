#!/usr/bin/env node
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const themePath = path.join(root, "apps/web/src/styles/theme.css");
const tokenPath = path.join(root, "apps/web/src/ds/tokens.ts");
const outPath = path.join(root, "apps/web/DESIGN.md");
const check = process.argv.includes("--check");

const theme = await readFile(themePath, "utf8");
const tokenSource = await readFile(tokenPath, "utf8");
const tokenNames = [...tokenSource.matchAll(/"(--[a-z0-9-]+)": "theme\.css"/g)].map((match) => match[1]);
assert.ok(tokenNames.length > 0, "Live DS token map must list theme.css sources.");

for (const token of tokenNames) {
  const escaped = token.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  assert.match(theme, new RegExp(`${escaped}\\s*:`), `${token} must exist in theme.css`);
}

const document = `# TLDR Astro live DESIGN.md

This is the agent-readable design system for the reader app. Tokens are measured from \`apps/web/src/styles/theme.css\`. Do not copy Vercel, ElevenLabs, or other DesignMD brand palettes onto this product. Do not invent colors, type, or spacing.

Generated by \`node scripts/generate-live-ds-design-md.mjs\`. Re-run after token changes. \`--check\` fails when this file is stale.

## Rationale

The live app is a reading product: Sky, Calendar, You, Friends, Learn. Semantic components determine meaning. Owner-authored writing determines vocabulary. Presentation uses the shared theme, then the live DS layers.

Newsreader is for titles. Body sans is for narrative. Geist Mono is for UI, labels, and the wordmark. Noto Sans Symbols is for glyphs only.

## Tokens

| Role | CSS variable |
| --- | --- |
${tokenNames.map((token) => `| \`${token}\` | \`${token}\` |`).join("\n")}

Components must use these variables. A \`clamp()\` or \`calc()\` in a component sheet still needs a documented semantic token first.

## Layers

| Layer | Lives in | Job |
| --- | --- | --- |
| Tokens | \`theme.css\`, \`apps/web/src/ds/tokens.ts\` | Named visual roles |
| Primitives | \`apps/web/src/ds/primitives.tsx\` | Stack, Inline, Box, Grid, Container, Text |
| Components | \`apps/web/src/ds/components.ts\` | Existing reader controls |
| Recipes | \`apps/web/src/ds/recipes.ts\` | Class strings, no JSX |
| Patterns | \`apps/web/src/ds/patterns.tsx\` | ReadingCard, Tabs, EmptyState, LoadingState |
| Page templates | \`apps/web/src/ds/page-templates.tsx\` | ReadingPage, ArticlePage |
| Catalog | \`apps/web/src/ds/catalog.ts\` | Pattern/block plan for new UI |

Lower layers must not import higher layers.

## Components

- Card: \`--card-bg\`, \`--card-border\`, \`--card-radius\`, \`--card-shadow\`, padding from \`--card-padding\`
- Pill: \`ui-pill\`, label type tokens, never body type
- Tabs: \`SegmentedControl\`
- Loading: \`PageLoading\`
- Article: \`article-page\` and body type tokens

## Anti-patterns

- Do not install DesignMD marketing blocks (hero, pricing, testimonial) into reader routes
- Do not add a heading or eyebrow without the surface heading contract
- Do not hardcode color, font, or spacing in feature CSS
- Do not compress owner-authored copy to fit a card
`;

if (check) {
  const current = await readFile(outPath, "utf8");
  assert.equal(current, document, "apps/web/DESIGN.md is stale. Run node scripts/generate-live-ds-design-md.mjs");
} else {
  await writeFile(outPath, document);
}

console.log(`Live DESIGN.md ${check ? "verified" : "written"} with ${tokenNames.length} theme tokens.`);
