function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function unquoteEnvValue(value) {
  const trimmed = value.trim();
  const quote = trimmed[0];

  if ((quote === "\"" || quote === "'") && trimmed.endsWith(quote)) {
    return trimmed.slice(1, -1);
  }

  return trimmed;
}

function loadLocalWebEnv() {
  if (process.env.NODE_ENV === "production") {
    return;
  }

  const envPath = path.join(repoRoot, "apps/web/.env.local");

  if (!fs.existsSync(envPath)) {
    return;
  }

  for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();

    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separatorIndex = trimmed.indexOf("=");

    if (separatorIndex <= 0) {
      continue;
    }

    const key = trimmed.slice(0, separatorIndex).trim();
    const value = unquoteEnvValue(trimmed.slice(separatorIndex + 1));

    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

function rowMap(rows, prefix) {
  return Object.fromEntries(
    rows
      .filter((row) => row.contentKey?.startsWith(`${prefix}/`))
      .map((row) => [
        row.contentKey.replace(`${prefix}/`, ""),
        String(row.body ?? "").trim()
      ])
      .filter(([, value]) => value)
  );
}

function requiredRows(map, label, expectedCount) {
  const count = Object.keys(map).length;

  if (count !== expectedCount) {
    throw new Error(`Expected ${expectedCount} ${label} rows, found ${count}.`);
  }
}

function rowCount(rows, prefix) {
  return rows.filter((row) => row.contentKey?.startsWith(`${prefix}/`) && String(row.body ?? "").trim()).length;
}

function hasRequiredDashboardLanguageRows(rows) {
  return rowCount(rows, "fallback-vocab/planet-topic") >= 11
    && rowCount(rows, "fallback-vocab/planet-core") >= 11
    && rowCount(rows, "fallback-vocab/angle-topic") >= 4
    && rowCount(rows, "fallback-vocab/sign-style") >= 12
    && rowCount(rows, "fallback-vocab/sign-need") >= 12
    && rowCount(rows, "fallback-vocab/house-life-area") >= 12
    && rowCount(rows, "fallback-vocab/aspect-verb") >= 5
    && rowCount(rows, "fallback-vocab/aspect-feel") >= 5
    && rowCount(rows, "fallback-vocab/sign-ruler") >= 12;
}

function dashboardHeaders(serviceRoleKey) {
  return {
    apikey: serviceRoleKey,
    authorization: `Bearer ${serviceRoleKey}`,
    "content-type": "application/json"
  };
}

function isMissingServingGuardColumn(payload) {
  const message = typeof payload?.message === "string" ? payload.message : "";
  const details = typeof payload?.details === "string" ? payload.details : "";

  return payload?.code === "42703"
    && /\b(lane|review_state)\b/i.test(`${message} ${details}`);
}

async function fetchDashboardRows(prefixes) {
  loadLocalWebEnv();

  const supabaseUrl = process.env.SUPABASE_URL ?? process.env.VITE_SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!supabaseUrl || !serviceRoleKey || process.env.TLDR_EMERGENCY_COPY_SOURCE !== "dashboard") {
    return null;
  }

  const rows = [];

  for (const prefix of prefixes) {
    const params = new URLSearchParams({
      select: "content_key,headline,summary,body,status,lane,review_state,source_snapshot,facts,updated_at",
      content_key: `like.${prefix}%`,
      status: "eq.LIVE",
      lane: "eq.serving",
      review_state: "is.null",
      limit: "1000",
      order: "content_key.asc"
    });
    const response = await fetch(`${supabaseUrl}/rest/v1/generated_interpretations?${params}`, {
      headers: dashboardHeaders(serviceRoleKey)
    });
    const payload = await response.json().catch(() => null);

    if (!response.ok) {
      if (isMissingServingGuardColumn(payload) && process.env.TLDR_EMERGENCY_COPY_REQUIRE_DASHBOARD !== "1") {
        console.warn("Dashboard emergency-copy query skipped: generated_interpretations is missing lane/review_state. Apply apps/web/supabase/migrations/20260711110000_generated_content_serving_lane.sql to enable dashboard-sourced generation.");
        return null;
      }

      throw new Error(`Dashboard fallback row query failed with ${response.status}: ${JSON.stringify(payload)}`);
    }

    rows.push(...payload.map((row) => ({
      contentKey: row.content_key,
      headline: row.headline ?? "",
      summary: row.summary ?? "",
      body: row.body ?? "",
      status: row.status,
      lane: row.lane,
      review_state: row.review_state,
      sourceSnapshot: row.source_snapshot ?? {},
      facts: row.facts ?? {},
      updatedAt: row.updated_at
    })));
  }

  return rows;
}

async function loadSource() {
  let dashboardRows = null;

  try {
    dashboardRows = await fetchDashboardRows(["fallback-vocab/", "fallback-template/", "fallback-hook/"]);
  } catch (error) {
    if (process.env.TLDR_EMERGENCY_COPY_REQUIRE_DASHBOARD === "1") {
      throw error;
    }

    console.warn(`Dashboard emergency-copy query skipped; using checked-in fallback language source instead. ${error instanceof Error ? error.message : String(error)}`);
  }

  if (dashboardRows?.length && hasRequiredDashboardLanguageRows(dashboardRows)) {
    const source = {
      _meta: {
        generated: true,
        warning: generatedWarning,
        source: "generated_interpretations LIVE serving dashboard rows",
        generatedAt: new Date().toISOString()
      },
      note: "Dashboard-authored fallback vocab and templates used by the local emergency composer.",
      templateRows: dashboardRows
    };

    fs.writeFileSync(cacheOutputPath, `${JSON.stringify(source, null, 2)}\n`);
    return {
      source,
      sourceLabel: "generated_interpretations LIVE serving dashboard rows"
    };
  }

  if (dashboardRows?.length) {
    console.warn("Dashboard emergency-copy rows are incomplete; using checked-in fallback language source instead.");
  }

  const languageSource = readJson(sourcePath);
  const templateSource = fs.existsSync(templateSourcePath)
    ? readJson(templateSourcePath)
    : { templateRows: [] };

  return {
    source: {
      ...languageSource,
      note: languageSource.note ?? "Dashboard-authored fallback vocab and templates used by the local emergency composer.",
      compositionRules: {
        ...(languageSource.compositionRules ?? {}),
        ...(templateSource.compositionRules ?? {})
      },
      templateRows: [
        ...(Array.isArray(languageSource.templateRows) ? languageSource.templateRows : []),
        ...(Array.isArray(templateSource.templateRows) ? templateSource.templateRows : [])
      ]
    },
    sourceLabel: `${path.relative(repoRoot, sourcePath)} + ${path.relative(repoRoot, templateSourcePath)}`
  };
}

