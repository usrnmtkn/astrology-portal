import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {build} from 'vite';
import {sharedReaderAuthoredRowsPlugin} from './reader-authored-sharing-plugin.mjs';
const source=new URL('../apps/web/src/content/fallbackArchitectureV3/bundled-transit-core-authored-cards-v3.json',import.meta.url);
const plugin=sharedReaderAuthoredRowsPlugin(),transform=plugin.transform;let transformed=false;
plugin.transform=(...args)=>{const result=transform(...args);if(result){transformed=true;assert(result.code.includes('shared['));}return result;};
const built=await build({configFile:false,logLevel:'silent',plugins:[plugin],build:{write:false,lib:{entry:source.pathname,formats:['es']},minify:true}});
assert(transformed,'The actual Vite build must execute the source-sharing transform.');
const chunk=(Array.isArray(built)?built:[built]).flatMap(result=>result.output).find(item=>item.type==='chunk');assert(chunk);
const module=await import(`data:text/javascript;base64,${Buffer.from(chunk.code).toString('base64')}`);
const original=JSON.parse(await fs.readFile(source,'utf8'));
assert.deepEqual(module.default,original,'Actual Vite output preserves every original field, complete source unit, order and approval record.');
assert.deepEqual(module.authoredCards,original.authoredCards);
const digest=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
assert.equal(digest(module.default),digest(original));
const shared=JSON.parse(await fs.readFile(new URL('../apps/web/src/content/fallbackArchitectureV3/deferred-base-reader-support-v1.json',import.meta.url),'utf8')).authoredCards;
for(const row of shared)assert.deepEqual(module.authoredCards.find(item=>item.contentKey===row.contentKey),row);
console.log(`PASS: actual Vite shared transport preserves all ${original.authoredCards.length} complete authored units and all ${shared.length} shared units, exact object hash, order and original approval fields.`);
