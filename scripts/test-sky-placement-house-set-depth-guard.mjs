import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  filterMixedDepthSkyPlacementHouseRows,
  incompleteOwnerAuthoredHousePlacementKeys
} from "../apps/web/src/content/fallbackArchitectureV3/skyPlacementHouseSetGuard.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const houseRows = JSON.parse(fs.readFileSync(
  path.join(root, "apps/web/src/content/fallbackArchitectureV3/bundled-sky-placement-house-rows-v3.json"),
  "utf8"
)).hookRows;
const ownerRows = JSON.parse(fs.readFileSync(
  path.join(root, "apps/web/src/content/fallbackArchitectureV3/authored-inputs/owner-authored-sky-placement-house-passages-v1.json"),
  "utf8"
)).rows;

const jupiterLeoPrefix = "house-horoscope-core/jupiter/leo/house-";
const uranusGeminiPrefix = "house-horoscope-core/uranus/gemini/house-";
const jupiterLeoRows = houseRows.filter((row) => row.contentKey.startsWith(jupiterLeoPrefix));
const uranusGeminiRows = houseRows.filter((row) => row.contentKey.startsWith(uranusGeminiPrefix));

assert.equal(jupiterLeoRows.length, 12, "The bundled Jupiter/Leo source still contains all 12 underlying house rows.");
assert.equal(ownerRows.filter((row) => row.contentKey.startsWith(jupiterLeoPrefix)).length, 7, "Current owner-authored Jupiter/Leo coverage must remain 7/12 until #537 is approved and promoted.");

const incomplete = incompleteOwnerAuthoredHousePlacementKeys(houseRows, ownerRows);
assert.deepEqual([...incomplete], ["jupiter/leo"], "Jupiter/Leo must be the partial owner-authored house set.");

const guarded = filterMixedDepthSkyPlacementHouseRows(houseRows, ownerRows);
assert.equal(guarded.filter((row) => row.contentKey.startsWith(jupiterLeoPrefix)).length, 0, "A partial owner-authored Jupiter/Leo set must fail closed as a whole set.");
assert.equal(guarded.filter((row) => row.contentKey.startsWith(uranusGeminiPrefix)).length, uranusGeminiRows.length, "Compact-only placements must remain available.");

const ownerByKey = new Map(ownerRows.map((row) => [row.contentKey, row]));
const simulatedCompleteOwnerRows = [...ownerRows];
for (const row of jupiterLeoRows) {
  if (ownerByKey.has(row.contentKey)) continue;
  simulatedCompleteOwnerRows.push({
    contentKey: row.contentKey,
    body_you: row.body_you,
    review_status: "approved"
  });
}
assert.equal(simulatedCompleteOwnerRows.filter((row) => row.contentKey.startsWith(jupiterLeoPrefix)).length, 12);
assert.equal(
  filterMixedDepthSkyPlacementHouseRows(houseRows, simulatedCompleteOwnerRows)
    .filter((row) => row.contentKey.startsWith(jupiterLeoPrefix)).length,
  12,
  "A complete 12/12 owner-authored set that matches the bundled reader rows must release automatically."
);

const mismatchedOwnerRows = simulatedCompleteOwnerRows.map((row) => (
  row.contentKey === `${jupiterLeoPrefix}1`
    ? { ...row, body_you: `${row.body_you} DRIFT` }
    : row
));
assert.equal(
  filterMixedDepthSkyPlacementHouseRows(houseRows, mismatchedOwnerRows)
    .filter((row) => row.contentKey.startsWith(jupiterLeoPrefix)).length,
  0,
  "A nominal 12/12 owner set must still fail closed if the bundled reader copy has not been regenerated byte-identically."
);

console.log("Sky placement house-set depth guard passed: partial/full drift fails closed; compact-only and complete matching sets remain available.");
