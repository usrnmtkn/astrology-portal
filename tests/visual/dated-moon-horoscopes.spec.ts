import {test,expect} from '@playwright/test';
import {fork} from 'node:child_process';
import path from 'node:path';
import {routeStudioInventoryApi} from '../helpers/studio-inventory-route';
import {MOON_HOROSCOPE_SIGNS,moonHoroscopeHouse,moonHoroscopeKey} from '../../src/shared/datedLunationHoroscopes.mjs';

for(const width of [390,1440])for(const theme of ['light','dark'])for(const phase of ['new-moon','full-moon'])test(`Write, save, publish and revise dated Moon horoscopes ${phase} ${width} ${theme}`,async({page})=>{
  const child=fork(path.resolve('tests/helpers/moon-horoscope-api.mts'),['--ipc'],{execArgv:['--import','tsx'],stdio:['ignore','pipe','pipe','ipc']});
  let sequence=0,stderr='';const pending=new Map<number,{resolve:(value:any)=>void;reject:(error:Error)=>void}>();
  child.stderr?.on('data',value=>stderr+=value);
  const ready=new Promise<void>((resolve,reject)=>{child.on('message',(message:any)=>{if(message.ready)return resolve();const task=pending.get(message.id);if(task){pending.delete(message.id);message.error?task.reject(new Error(message.error)):task.resolve(message.result);}});child.on('exit',code=>{const error=new Error(`Fixture exited ${code}: ${stderr}`);reject(error);pending.forEach(task=>task.reject(error));});});
  const call=(message:any)=>new Promise<any>((resolve,reject)=>{const id=++sequence;pending.set(id,{resolve,reject});child.send({...message,id});});
  try{
    await ready;
    let failEvents=width===1440&&theme==='light';
    const writes:any[]=[];
    await routeStudioInventoryApi(page,{call,onWrite:write=>writes.push(write),answer:async(route,url)=>{
      if(url.pathname!=='/api/admin/lunation-writing')return false;
      if(failEvents){failEvents=false;await route.fulfill({status:503,json:{ok:false,error:'Synthetic event lookup unavailable.'}});return true;}
      const result=await call({method:route.request().method(),url:url.pathname+url.search});
      await route.fulfill({status:result.status,json:result.payload});return true;
    }});
    await page.setViewportSize({width,height:1000});
    await page.addInitScript(theme=>{localStorage.setItem('tldrastro:contentAdminSecret','calendar-api-fixture');localStorage.setItem('tldrastro:studio-theme',theme);},theme);
    await page.goto('/admin/content#horoscopes');
    const titleStyle=await page.getByRole('heading',{level:1,name:'Horoscopes',exact:true}).evaluate(el=>{const s=getComputedStyle(el);return [s.fontFamily,s.fontSize,s.fontWeight,s.lineHeight,s.letterSpacing,s.marginTop,s.marginBottom,s.textTransform,s.textAlign];});
    if(width===390)await page.getByRole('button',{name:'Open Content Studio navigation',exact:true}).click();
    await page.getByRole('navigation',{name:'Content operations'}).getByRole('button',{name:'New & Full Moon horoscopes',exact:true}).click();
    const studio=page.getByRole('region',{name:'Dated Moon horoscopes',exact:true});
    if(width===1440&&theme==='light'){
      await expect(studio.getByRole('alert')).toHaveText('Synthetic event lookup unavailable.');
      await studio.getByRole('button',{name:'Reload events',exact:true}).click();
    }
    await studio.getByLabel('Month',{exact:true}).fill('2026-12');
    const events=await call({method:'GET',url:'/api/admin/lunation-writing?month=2026-12&timeZone=America%2FNew_York'});
    const event=events.payload.events.find((e:any)=>e.phase===phase);
    await studio.getByText(/^Time zone ·/).click();
    await studio.getByLabel('Time zone',{exact:true}).fill('America/New_York');
    await expect(studio.getByLabel('Moon event',{exact:true})).toContainText(event.title);
    await studio.getByLabel('Moon event',{exact:true}).selectOption(event.id);
    await studio.getByRole('button',{name:'Open Moon horoscopes',exact:true}).click();
    expect(await studio.getByRole('heading',{level:2,name:event.title,exact:true}).evaluate(el=>{const s=getComputedStyle(el);return [s.fontFamily,s.fontSize,s.fontWeight,s.lineHeight,s.letterSpacing,s.marginTop,s.marginBottom,s.textTransform,s.textAlign];})).toEqual(titleStyle);
    const chooseSign=async(value:string)=>{if(width<900)await studio.getByLabel('Moon horoscope sign',{exact:true}).selectOption(value);else await studio.getByRole('navigation',{name:'Moon readings by sign'}).getByRole('button',{name:new RegExp(`^${value[0].toUpperCase()+value.slice(1)}(?: ✓)?$`)}).click();};
    const more=async()=>{const details=studio.getByLabel('Moon horoscope actions',{exact:true});if(await details.getAttribute('open')===null)await details.locator('summary').click();};
    const stored=async()=> (await call({method:'rows'})).filter((row:any)=>row.content_key===moonHoroscopeKey(event));
    const manual='  A complete manual opening.\n\nA complete manual ending.  ';
    await studio.getByLabel('Complete horoscope',{exact:true}).fill(manual);
    await chooseSign('taurus');await studio.getByLabel('Complete horoscope',{exact:true}).fill('Taurus private writing.');
    await chooseSign('aries');await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(manual);
    await studio.getByRole('button',{name:'Save draft',exact:true}).click();await expect(studio.getByRole('status')).toHaveText('Draft saved.');
    await expect(studio.getByRole('button',{name:'Publish',exact:true})).toBeDisabled();
    const raw=(await call({method:'rows'})).find((row:any)=>row.sections?.moonWritingDraft);expect(raw.lane).toBe('reference');expect(raw.sections.moonWritingDraft.section.passages[0].body).toBe(manual);
    expect((await call({method:'reader',body:{keys:[raw.content_key]}})).payload.rows).toHaveLength(0);
    await page.reload();await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(manual);
    await chooseSign('taurus');await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue('Taurus private writing.');
    await chooseSign('aries');
    await studio.getByText('Import 12 readings',{exact:true}).click();
    await studio.getByLabel('All twelve horoscopes',{exact:true}).fill('Aries / Aries Rising\nOnly one reading.');
    await studio.getByRole('button',{name:'Import readings',exact:true}).click();
    await expect(studio.getByRole('alert')).toBeVisible();expect(await stored()).toHaveLength(0);
    const source=MOON_HOROSCOPE_SIGNS.map(sign=>`${sign} / ${sign} Rising\n${phase==='new-moon'?'New':'Full'} Moon in Your ${moonHoroscopeHouse(event.sign,sign)}th House\n${sign} complete synthetic opening.\n\n${sign} complete synthetic final sentence.`).join('\n\n');
    await studio.getByLabel('All twelve horoscopes',{exact:true}).fill(source);
    await studio.getByRole('button',{name:'Import readings',exact:true}).click();
    await expect(studio.getByRole('heading',{level:3,name:`Aries / Aries Rising · House ${moonHoroscopeHouse(event.sign,'aries')}`,exact:true})).toHaveText(`Aries / Aries Rising · House ${moonHoroscopeHouse(event.sign,'aries')}`);
    await expect(studio.locator('.studio-entry-navigation button')).toHaveCount(12);
    await studio.getByRole('button',{name:'Save draft',exact:true}).click();
    await expect(studio.getByRole('status')).toHaveText('Draft saved.');
    let rows=await stored();expect(rows).toHaveLength(1);expect(rows[0].source_snapshot.editorialImport.originalSource).toBe(source);
    const beforeReplacement=structuredClone(rows),reviewedBody=rows[0].sections.articleHoroscopes.passages[0].body,writesBeforeReplacement=writes.length;
    const replacement=source.replaceAll('complete synthetic','replacement synthetic');
    const save=studio.getByRole('button',{name:'Save draft',exact:true});
    const replacementField=studio.getByLabel('All twelve horoscopes',{exact:true});
    await replacementField.fill(replacement);
    await expect(save).toBeDisabled();
    await expect(studio.getByText('Import or clear the pasted readings before saving.',{exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:`test-results/dated-moon-pending-replacement-${width}-${theme}.png`,fullPage:true});
    page.once('dialog',dialog=>dialog.dismiss());
    await studio.getByRole('button',{name:'Choose another Moon',exact:true}).click();
    await expect(replacementField).toHaveValue(replacement);
    expect(await stored()).toEqual(beforeReplacement);
    expect(writes).toHaveLength(writesBeforeReplacement);
    await studio.getByRole('button',{name:'Clear paste',exact:true}).click();
    await expect(replacementField).toHaveValue('');
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(reviewedBody);
    await expect(save).toBeDisabled();
    expect(await stored()).toEqual(beforeReplacement);
    expect(writes).toHaveLength(writesBeforeReplacement);
    await replacementField.fill(replacement);
    await studio.getByRole('button',{name:'Import readings',exact:true}).click();
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(reviewedBody.replaceAll('complete synthetic','replacement synthetic'));
    await expect(save).toBeEnabled();await save.click();
    await expect(studio.getByRole('status')).toHaveText('Draft saved.');
    rows=await stored();expect(rows[0].source_snapshot.editorialImport.originalSource).toBe(replacement);
    const replacementPassages=beforeReplacement[0].sections.articleHoroscopes.passages.map((p:any)=>({...p,body:p.body.replaceAll('complete synthetic','replacement synthetic')}));
    expect(rows[0].sections.articleHoroscopes.passages).toEqual(replacementPassages);
    expect(writes.at(-1).body.sections.articleHoroscopes.passages).toEqual(replacementPassages);
    expect(writes.at(-1).body.sourceSnapshot.editorialImport.originalSource).toBe(replacement);
    if(width===1440&&theme==='light'){
      const changed=await call({method:'PATCH',body:{id:rows[0].id,expectedUpdatedAt:rows[0].updated_at,reviewerNotes:'Synthetic concurrent metadata change.'}});expect(changed.status).toBe(200);
      await studio.getByLabel('Complete horoscope',{exact:true}).fill('An unsaved local reading must survive a save conflict.');
      await studio.getByRole('button',{name:'Save draft',exact:true}).click();
      await expect(studio.getByRole('alert')).toContainText('changed');
      await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue('An unsaved local reading must survive a save conflict.');
      page.once('dialog',dialog=>dialog.accept());
      await more();await studio.getByRole('button',{name:'Reload saved version',exact:true}).click();
      await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(rows[0].sections.articleHoroscopes.passages[0].body);
    }
    await page.reload();
    await expect(studio.locator('.studio-entry-navigation button')).toHaveCount(12);
    await chooseSign('pisces');
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(rows[0].sections.articleHoroscopes.passages[11].body);
    await studio.getByRole('button',{name:'Publish',exact:true}).click();
    await expect(studio.getByRole('checkbox')).toBeInViewport();
    await studio.getByRole('checkbox').check();await studio.getByRole('button',{name:'Publish Moon horoscopes',exact:true}).click();
    await expect(studio.getByRole('status')).toContainText('Published. These twelve readings');
    rows=await stored();const published=rows[0];expect(published.status).toBe('LIVE');
    const publicResult=await call({method:'reader',body:{keys:[published.content_key]}});expect(publicResult.payload.rows[0].sections.articleHoroscopes.passages).toEqual(published.sections.articleHoroscopes.passages);expect(JSON.stringify(publicResult.payload)).not.toContain('originalSource');
    await page.screenshot({path:`test-results/dated-moon-horoscopes-${width}-${theme}.png`,fullPage:true});
    const publishPosition=await studio.getByRole('button',{name:'Publish',exact:true}).boundingBox();expect(publishPosition!.y).toBeGreaterThanOrEqual(0);expect(publishPosition!.y).toBeLessThan(1000);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    const exact=published.sections.articleHoroscopes.passages[11].body+'\n\nA complete revision ending.';
    await studio.getByLabel('Complete horoscope',{exact:true}).fill(exact);await studio.getByRole('button',{name:'Save draft',exact:true}).click();
    await expect(studio.getByRole('status')).toHaveText('Draft saved.');
    rows=await stored();expect(rows.find((row:any)=>row.id===published.id).body).toBe(published.body);expect(rows.find((row:any)=>row.mode==='studio-draft').sections.articleHoroscopes.passages[11].body).toBe(exact);
    await studio.getByRole('checkbox').check();await studio.getByRole('button',{name:'Publish Moon horoscopes',exact:true}).click();
    await expect(studio.getByRole('status')).toContainText('Published. These twelve readings');
    rows=await stored();expect(rows.find((row:any)=>row.id===published.id).sections.articleHoroscopes.passages[11].body).toBe(exact);
    if(width===1440&&theme==='light'){
      await studio.getByLabel('Complete horoscope',{exact:true}).fill(exact+'\n\nAnother private revision.');
      await studio.getByRole('button',{name:'Save draft',exact:true}).click();
      await expect(studio.getByRole('status')).toHaveText('Draft saved.');
      await more();page.once('dialog',dialog=>dialog.accept());await studio.getByRole('button',{name:'Archive draft revision',exact:true}).click();
      await expect(studio.getByRole('status')).toHaveText('Draft revision archived. The current published readings are open.');
      await chooseSign('pisces');
      await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(exact);
    }
    const beforeArchive=(await call({method:'rows'})).find((row:any)=>row.id===published.id);
    await more();
    const archive=studio.getByRole('button',{name:'Archive Moon horoscopes',exact:true});
    await studio.getByLabel('Complete horoscope',{exact:true}).fill(exact+' Unsaved.');
    await expect(archive).toBeDisabled();
    await studio.getByLabel('Complete horoscope',{exact:true}).fill(exact);
    await expect(archive).toBeEnabled();
    page.once('dialog',dialog=>dialog.accept());await archive.click();
    await expect(studio.getByRole('status')).toHaveText('Moon horoscopes archived. These readings are no longer published.');
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toBeDisabled();
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(exact);
    await expect(studio.getByRole('button',{name:'Publish Moon horoscopes',exact:true})).toHaveCount(0);
    let retired=(await call({method:'rows'})).find((row:any)=>row.id===published.id);
    expect(retired.status).toBe('ARCHIVED');
    for(const field of ['headline','summary','body','facts','sections','source_snapshot'])expect(retired[field]).toEqual(beforeArchive[field]);
    expect((await call({method:'reader',body:{keys:[published.content_key]}})).payload.rows).toHaveLength(0);
    await page.reload();
    await more();await expect(studio.getByRole('button',{name:'Restore as draft',exact:true})).toBeVisible();
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toBeDisabled();
    await chooseSign('aries');
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toHaveValue(beforeArchive.sections.articleHoroscopes.passages[0].body);
    await studio.getByRole('button',{name:'Choose another Moon',exact:true}).click();
    await studio.getByLabel('Month',{exact:true}).fill('2026-12');
    await studio.getByRole('combobox',{name:'Moon event',exact:true}).selectOption(event.id);
    await studio.getByRole('button',{name:'Open Moon horoscopes',exact:true}).click();
    await more();await expect(studio.getByRole('button',{name:'Restore as draft',exact:true})).toBeVisible();
    await studio.getByRole('button',{name:'Restore as draft',exact:true}).click();
    await expect(studio.getByRole('status')).toHaveText('Moon horoscopes restored as a draft. Review and publish when ready.');
    await expect(studio.getByLabel('Complete horoscope',{exact:true})).toBeEnabled();
    expect((await call({method:'reader',body:{keys:[published.content_key]}})).payload.rows).toHaveLength(0);
    await page.reload();
    await studio.getByRole('checkbox').check();
    await studio.getByRole('button',{name:'Publish Moon horoscopes',exact:true}).click();
    await expect(studio.getByRole('status')).toContainText('Published. These twelve readings');
    const republished=(await call({method:'reader',body:{keys:[published.content_key]}})).payload.rows[0];
    expect(republished.sections.articleHoroscopes.passages).toEqual(beforeArchive.sections.articleHoroscopes.passages);
    await more();page.once('dialog',dialog=>dialog.accept());await studio.getByRole('button',{name:'Archive Moon horoscopes',exact:true}).click();
    await expect(studio.getByRole('status')).toHaveText('Moon horoscopes archived. These readings are no longer published.');
    expect((await call({method:'reader',body:{keys:[published.content_key]}})).payload.rows).toHaveLength(0);
  }finally{child.kill();}
});
