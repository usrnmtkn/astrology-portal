import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {servingPackageRecords} from '../../api/_lib/serving-package-records';
import {lunationPublicationDraft} from '../helpers/lunation-publication.mjs';
import {studioApiStore} from '../helpers/studio-api-store';
import {routeStudioInventoryApi} from '../helpers/studio-inventory-route';
import {normalizeNatalPlacementPreviewInput,renderNatalPlacementPreviewState} from '../../api/admin/natal-placement-preview';

const key='fallback-hook/house-meaning/4';
const legacyKey='fallback-hook/natal/planet-intro/saturn';
const legacyBody='Synthetic complete legacy opening.\n\nSynthetic legacy final sentence.';
const original=structuredClone(servingPackageRecords.get(key)!);
for(const width of [390,1440]) for(const theme of ['light','dark']) test(`Find, insert, save and export supported variables ${width} ${theme}`,async({page})=>{
  const fixture={...lunationPublicationDraft(),id:'house-variable-fixture',content_key:key,surface:'natal',block_type:'fallback_hook',
    event_type:'fallback-hook',body:original.body_you,sections:{packageRecord:original,packageOriginalRecord:original,packageDraft:original}};
  const store=await studioApiStore([fixture,{...lunationPublicationDraft(),id:'legacy-variable-source-fixture',content_key:legacyKey,surface:'natal',block_type:'fallback_hook',body:legacyBody,sections:{}}]);
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.setViewportSize({width,height:1000});
    await page.addInitScript(theme=>{localStorage.setItem('tldrastro:contentAdminSecret','calendar-api-fixture');localStorage.setItem('tldrastro:studio-theme',theme);},theme);
    await routeStudioInventoryApi(page,{call:store.call,answer:async(route,url)=>{
      if(url.pathname!=='/api/admin/natal-placement-preview')return false;
      const result=renderNatalPlacementPreviewState(normalizeNatalPlacementPreviewInput(route.request().postDataJSON()));
      await route.fulfill({json:{ok:true,...result}});return true;
    }});
    await page.goto('/admin/content#exact-content?category=Natal+Chart&planet=saturn&sign=virgo&house=4');
    const card=page.locator('.admin-natal-source-card').filter({has:page.locator('code').filter({hasText:key})});
    await card.getByRole('button',{name:/Edit|Load and edit/}).click();
    const editor=page.getByRole('dialog',{name:'Generated content editor',exact:true});
    const field=editor.getByRole('textbox',{name:'Reader phrase · You',exact:true});
    await field.fill('Synthetic {{planetTitle}} in your 4th house: ');
    await field.press('End');
    await editor.getByRole('button',{name:/^Variables \(/}).click();
    const rail=page.getByRole('complementary',{name:'Template variable reference'});
    await rail.getByRole('searchbox',{name:'Find a variable'}).fill('planetTopic');
    await expect(rail.getByRole('button',{name:'Insert {{planetTopic}}',exact:true})).toBeVisible();
    await rail.getByLabel('Only variables used in this row').check();
    await expect(rail.getByRole('button',{name:'Insert {{planetTopic}}',exact:true})).toHaveCount(0);
    await rail.getByLabel('Only variables used in this row').uncheck();
    await rail.getByRole('button',{name:'Insert {{planetTopic}}',exact:true}).click();
    await expect(field).toHaveValue('Synthetic {{planetTitle}} in your 4th house: {{planetTopic}}');
    await rail.getByRole('button',{name:'Close variables',exact:true}).click();
    const you='Synthetic {{planetTitle}} in your {{houseOrdinal}} house: {{planetTopic}}.';
    const they='Synthetic friend {{planetTitle}} in their {{houseOrdinal}} house: {{planetTopic}}.';
    await field.fill(you);
    await editor.getByRole('textbox',{name:'Reader phrase · They',exact:true}).fill(they);
    await editor.getByRole('button',{name:/^Save draft(?: & return)?$/}).click();
    await expect.poll(async()=>{const rows=await store.call({method:'rows'});return rows.find((row:any)=>row.id===fixture.id)?.sections.packageDraft.body_you;}).toBe(you);
    if(await editor.isVisible())await editor.getByRole('button',{name:'Close',exact:true}).click();
    await page.reload();
    await card.getByRole('button',{name:/Edit|Load and edit/}).click();
    await expect(field).toHaveValue(you);
    await expect(editor.getByRole('textbox',{name:'Reader phrase · They',exact:true})).toHaveValue(they);
    await page.screenshot({path:`test-results/variables-house-saved-${width}-${theme}.png`,fullPage:true});
    await editor.getByRole('button',{name:'Close',exact:true}).click();
    await page.goto('/admin/content#variables');
    const directory=page.getByRole('region',{name:'Variable directory',exact:true});
    await expect(directory.getByLabel('Library',{exact:true})).toHaveValue('');
    await directory.getByLabel('Search variables',{exact:true}).fill('planetTopic saturn');
    const topic=directory.getByRole('article').filter({has:page.getByRole('heading',{name:'{{planetTopic}}',exact:true})});
    await topic.getByRole('button',{name:'Open writing',exact:true}).click();
    await expect(editor.locator('textarea[data-sky-field="body"]')).toHaveValue('structure and limits');
    await editor.getByRole('button',{name:'Close',exact:true}).click();
    await directory.getByLabel('Search variables',{exact:true}).fill('houseMeaning');
    const house=directory.getByRole('article').filter({has:page.getByRole('heading',{name:'{{houseMeaning}}',exact:true})});
    await expect(house).toBeVisible();
    await house.locator('summary').filter({hasText:'Where it is used'}).click();
    await expect(house.locator('.studio-variable-usage')).toContainText('Fields: body');
    await house.getByRole('searchbox',{name:'Find writing for {{houseMeaning}}',exact:true}).fill('house-meaning/4');
    await house.getByRole('button',{name:'Open writing',exact:true}).click();
    await expect(field).toHaveValue(you);
    await editor.getByRole('button',{name:'Close',exact:true}).click();
    const downloaded=page.waitForEvent('download');
    await directory.getByRole('button',{name:'Export all values (JSON)',exact:true}).click();
    const download=await downloaded;
    const data=JSON.parse(await readFile((await download.path())!,'utf8'));
    expect(data.schema).toBe('studio-variable-export/v1');
    expect(data.rows.some((row:any)=>row.token==='{{planetTopic}}'&&row.content==='structure and limits')).toBe(true);
    expect(data.rows.some((row:any)=>row.type==='Condition')).toBe(true);
    const houseRows=data.rows.filter((row:any)=>row.token==='{{houseMeaning}}');
    expect(new Set(houseRows.map((row:any)=>row.sourceKey)).size).toBe(12);
    expect(houseRows.some((row:any)=>row.sourceKey===key&&row.field==='body_you'&&row.version==='Saved draft'&&row.content===you)).toBe(true);
    expect(houseRows.every((row:any)=>typeof row.allowedFields==='string'&&row.allowedFields.includes('fallback-template/natal.house-context'))).toBe(true);
    for(const token of ['{{placementHouseSentences}}','{{modifierSentences}}','{{planetIntro}}','{{natalCore}}']) expect(data.rows.some((row:any)=>row.token===token&&row.contentStatus==='Has content')).toBe(true);
    expect(data.rows.some((row:any)=>row.token==='{{planetIntro}}'&&row.sourceKey===legacyKey&&row.field==='body'&&row.content===legacyBody)).toBe(true);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  }finally{store.close();}
});
